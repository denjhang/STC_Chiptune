/* ========== 通道状态 (参考 fm.c FmOp) ========== */
static struct {
    u16 pos;
    u16 step;
    u8  vol;
    u8  env_state;
    u8  env_cnt;
    u8  atk;
    u8  decy;
    u8  sul;
    u8  sus;
    u8  rel;
    u8  level;
    u8  wave_idx;
    u8  env_step;
} wt_ch[WT_CHANS];

static u8 wt_voice_active;

/* 音色模板 (全局共用, 参考 fm_tone) */
static struct {
    u8 atk, decy, sul, sus, rel;
    u8 wave_idx;
} wt_tone;

static u8 wt_wait_cnt;

/* ========== 音色模板应用到通道 (参考 fm_apply_tone) ========== */
static void wt_apply_tone(u8 ch) {
    wt_ch[ch].atk  = wt_tone.atk;
    wt_ch[ch].decy = wt_tone.decy;
    wt_ch[ch].sul  = wt_tone.sul;
    wt_ch[ch].sus  = wt_tone.sus;
    wt_ch[ch].rel  = wt_tone.rel;
    wt_ch[ch].wave_idx = wt_tone.wave_idx;
}

/* ========== 包络更新 (参考 fm_env_tick) ========== */
static void wt_env_tick(u8 ch) {
    u8 cnt, step, lvl;

    cnt = wt_ch[ch].env_cnt;
    step = wt_ch[ch].env_step;
    if (cnt >= step) {
        wt_ch[ch].env_cnt = cnt - step;
        return;
    }

    wt_ch[ch].env_cnt = 250;
    lvl = wt_ch[ch].level;

    switch (wt_ch[ch].env_state) {
    case 1: /* attack */
        lvl++;
        if (lvl >= 31) {
            wt_ch[ch].env_state = 2;
            wt_ch[ch].env_step = wt_ch[ch].decy;
        }
        wt_ch[ch].level = lvl;
        break;
    case 2: /* decay */
        if (lvl > 0) lvl--;
        wt_ch[ch].level = lvl;
        if (lvl == wt_ch[ch].sul) {
            wt_ch[ch].env_state = 3;
            wt_ch[ch].env_step = wt_ch[ch].sus;
        }
        break;
    case 3: /* sustain */
        if (lvl > 0) lvl--;
        wt_ch[ch].level = lvl;
        if (lvl == 0) wt_ch[ch].step = 0;
        break;
    case 4: /* release */
        if (lvl > 0) lvl--;
        wt_ch[ch].level = lvl;
        if (lvl == 0) {
            wt_ch[ch].step = 0;
            wt_voice_active &= ~(1 << ch);
        }
        break;
    }
}

/* ========== 公开函数 ========== */

void wt_init(void) {
    u8 i;

    wt_tone.atk = wt_env_cnt[14];
    wt_tone.decy = wt_env_cnt[9];
    wt_tone.sul = 13;
    wt_tone.sus = wt_env_cnt[3];
    wt_tone.rel = wt_env_cnt[7];
    wt_tone.wave_idx = 1;

    for (i = 0; i < WT_CHANS; i++) {
        wt_ch[i].pos = 0;
        wt_ch[i].step = 0;
        wt_ch[i].vol = 31;
        wt_ch[i].env_state = 0;
        wt_ch[i].env_cnt = 0;
        wt_ch[i].level = 0;
        wt_ch[i].wave_idx = 1;
        wt_ch[i].env_step = 0;
    }
    wt_voice_active = 0;
    wt_wait_cnt = 0;
}

void wt_wr(u8 addr, u8 dat) {
    u8 ch, note;
    u16 f;

    if (addr < 0x04) {
        ch = addr;
        note = dat;
        if (note < 24) note = 24;
        if (note > 127) note = 127;
        note -= 24;
        f = wt_note_freq[note];

        wt_apply_tone(ch);

        wt_ch[ch].step = f;
        wt_ch[ch].pos = 0;
        wt_ch[ch].env_state = 1;
        wt_ch[ch].env_cnt = 250;
        wt_ch[ch].level = 0;
        wt_ch[ch].env_step = wt_ch[ch].atk;
        wt_voice_active |= (1 << ch);

    } else if (addr < 0x08) {
        ch = addr - 4;
        if (wt_ch[ch].step == 0) return;
        wt_ch[ch].env_state = 4;
        wt_ch[ch].env_step = wt_ch[ch].rel;

    } else if (addr < 0x0C) {
        ch = addr - 8;
        wt_ch[ch].vol = dat & 0x1F;

    } else if (addr == 0x10) {
        wt_tone.atk = wt_env_cnt[(dat >> 4) & 0x0F];
        wt_tone.decy = wt_env_cnt[dat & 0x0F];

    } else if (addr == 0x11) {
        wt_tone.sul = (dat >> 4) & 0x0F;
        wt_tone.sul = wt_tone.sul == 15 ? 0 : 31 - wt_tone.sul * 2;
        wt_tone.sus = wt_env_cnt[dat & 0x0F];

    } else if (addr == 0x12) {
        wt_tone.rel = wt_env_cnt[dat & 0x0F];

    } else if (addr == 0x13) {
        wt_tone.wave_idx = dat % 6;
    }
}

s16 wt_render(void) {
    u8 ch, idx, lvl, vol, wi;
    s8 wave_val;
    s16 ch_out, total;
    u16 pos, step;

    wt_wait_cnt++;
    wt_wait_cnt &= 0x03;

    total = 0;

    for (ch = 0; ch < WT_CHANS; ch++) {
        if (wt_ch[ch].step == 0) continue;

        pos = wt_ch[ch].pos;
        step = wt_ch[ch].step;
        pos += step;
        wt_ch[ch].pos = pos;

        idx = (u8)(pos >> 8);

        wi = wt_ch[ch].wave_idx;
        wave_val = wt_waves[(u16)(wi << 6) | idx];

        if (wt_wait_cnt == ch) {
            wt_env_tick(ch);
        }

        lvl = wt_ch[ch].level;
        vol = wt_ch[ch].vol;
        ch_out = (s16)wave_val * (s16)(lvl + 1) * (s16)(vol + 1);
        ch_out >>= 10;

        total += ch_out;
    }

    return total;
}

u8 wt_channel_mask(void) {
    u8 mask = 0, i;
    for (i = 0; i < WT_CHANS; i++) {
        if (wt_ch[i].step) {
            mask |= (1 << i);
        }
    }
    return mask;
}
