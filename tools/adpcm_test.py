DRUM_NAMES = ['BD', 'SD', 'TC', 'HH', 'TM', 'RS']
BD, SD, TC, HH, TM, RS = 0, 1, 2, 3, 4, 5

def pcm_send(ser, addr, data):
    chk = 0xC0 ^ addr ^ data
    ser.write(bytes([0xC0, addr, data, chk]))
    time.sleep(0.002)
    resp = ser.read(1)
    return resp and resp[0] == 0xAA

def note_on(ser, ch, drum):
    pcm_send(ser, 0x15 | ch, drum)

def note_off(ser, ch):
    pcm_send(ser, 0x1B | ch, 0)

def set_vol(ser, ch, vol):
    pcm_send(ser, 0x21 | ch, vol)

def tick(delay):
    time.sleep(delay)

# 16 步序列器: 每步是 (BD, SD, HH, TC, TM, RS) 的 bool 元组
def play_pattern(ser, pattern, bpm, bars=2, swing=0.0):
    step_dur = 60.0 / bpm / 4  # 16th note duration
    steps_per_bar = len(pattern)
    for _ in range(bars):
        for i, step in enumerate(pattern):
            if step[0]: note_on(ser, 0, BD)
            if step[1]: note_on(ser, 1, SD)
            if step[2]: note_on(ser, 2, TC)
            if step[3]: note_on(ser, 3, HH)
            if step[4]: note_on(ser, 4, TM)
            if step[5]: note_on(ser, 5, RS)
            d = step_dur
            if swing > 0 and i % 2 == 0:
                d *= (1 + swing)
            elif swing > 0 and i % 2 == 1:
                d *= (1 - swing)
            tick(d)

