    time.sleep(0.1)
    ser.reset_input_buffer()

    for ch in range(6):
        set_vol(ser, ch, 24)

    rhythms = RHYTHMS if idx < 0 else [RHYTHMS[idx]]

    for name, pattern, bpm, bars in rhythms:
        print(f">> {name}  BPM={bpm}  bars={bars}")
