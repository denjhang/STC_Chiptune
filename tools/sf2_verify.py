STEP_INC = [-16, -16, -16, -16, 32, 80, 112, 144]


def adpcm_encode(pcm):
    nibbles = []; acc = 0; step_idx = 0
    for s in pcm:
        if s > 2047: s = 2047
        if s < -2048: s = -2048
        row = step_idx // 16
        best = 0; bd = abs(s - acc)
        for n in range(16):
            d = JEDI_FLAT[row * 16 + n]
            t = acc + d; t &= 0xFFF
            if t & 0x800: t |= ~0xFFF
            if abs(s - t) < bd:
                bd = abs(s - t); best = n
        d = JEDI_FLAT[row * 16 + best]
        acc += d; acc &= 0xFFF
        if acc & 0x800: acc |= ~0xFFF
        step_idx += STEP_INC[best & 7]
        if step_idx < 0: step_idx = 0
        if step_idx > 768: step_idx = 768
        nibbles.append(best)
    return nibbles


def adpcm_decode(nibbles):
    acc = 0; step = 0; out = []
    for n in nibbles:
        d = JEDI_FLAT[step + n]
        acc += d; acc &= 0xFFF
        if acc & 0x800: acc |= ~0xFFF
        out.append(acc)
        step += STEP_INC[n & 7]
        if step < 0: step = 0
        if step > 768: step = 768
    return out


INSTRUMENTS = [
    ('01_piano.wav',      'Piano'),
    ('02_slapbass.wav',   'SlapBass'),
    ('03_shakuhachi.wav', 'Shakuhachi'),
    ('04_oboe.wav',       'Oboe'),
    ('05_trumpet.wav',    'Trumpet'),
    ('06_blow.wav',       'Blow'),
    ('07_oboe2.wav',      'Oboe2'),
    ('08_strings.wav',    'Strings'),
    ('09_harp.wav',       'Harp'),
    ('10_guitar.wav',     'Guitar'),
]

for wav_name, display in INSTRUMENTS:
    with wave.open(os.path.join(WAV_DIR, wav_name), 'r') as w:
        raw = w.readframes(w.getnframes())
    pcm16 = list(struct.unpack('<%dh' % (len(raw) // 2), raw))
    n = len(pcm16)
    peak = max(abs(s) for s in pcm16)
    scale = 2047.0 / peak if peak > 0 else 1.0
    norm = [int(s * scale) for s in pcm16]

    nibs = adpcm_encode(norm)
    dec = adpcm_decode(nibs)

    # 打包成字节 (和 gen_adpcm_rom.py 一样)
    rom_bytes = bytearray()
    for i in range(0, len(nibs), 2):
        hi = nibs[i]
        lo = nibs[i + 1] if i + 1 < len(nibs) else 0
        rom_bytes.append((hi << 4) | lo)

    # 从 ROM 字节重新解码 (模拟 C 代码从 SF2_ROM[] 读取)
    dec2 = []
    acc2 = 0; step2 = 0
    for i in range(len(nibs)):
        addr_byte = i >> 1
        byte_val = rom_bytes[addr_byte]
        if i & 1:
            nib = byte_val & 0x0F
        else:
            nib = (byte_val >> 4) & 0x0F
        d = JEDI_FLAT[step2 + nib]
        acc2 += d; acc2 &= 0xFFF
        if acc2 & 0x800: acc2 |= ~0xFFF
        dec2.append(acc2)
        step2 += STEP_INC[nib & 7]
        if step2 < 0: step2 = 0
        if step2 > 768: step2 = 768

    # SNR: 直接 decode vs 打包后再 decode
    pack_diff = [a - b for a, b in zip(dec, dec2)]
    max_pack_diff = max(abs(d) for d in pack_diff) if pack_diff else 0

    # SNR: original vs decoded
    noise = [o - t for o, t in zip(dec, norm)]
    rms_s = sum(s ** 2 for s in norm) ** 0.5
    rms_n = sum(nn ** 2 for nn in noise) ** 0.5
    snr = 20 * math.log10(rms_s / rms_n) if rms_n > 0 else 99
    max_err = max(abs(nn) for nn in noise)

    out_path = os.path.join(OUT_DIR, wav_name)
    with wave.open(out_path, 'w') as wf:
        wf.setnchannels(1)
        wf.setsampwidth(2)
        wf.setframerate(17640)
        wf.writeframes(struct.pack('<%dh' % len(dec), *dec))

    print(f'{display:12s} n={n:5d} nibs={len(nibs):5d} rom={len(rom_bytes):5d}B '
          f'SNR={snr:5.1f}dB maxerr={max_err:4d} pack_diff={max_pack_diff} '
          f'-> {out_path}')
